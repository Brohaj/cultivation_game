// Обратная совместимость — SECT_RANKS как alias
const SECT_RANKS = SECT_RANKS_BASE;

// Динамические пороги рангов для конкретной секты
function getSectRanks(sectId) {
    const sect = SECTS.find(s => s.id === sectId);
    const diff = sect ? SECT_DIFFICULTY[sect.difficulty] : SECT_DIFFICULTY.medium;
    const entryRealm = sect ? (sect.requirement.realm || 0) : 0;
    return SECT_RANKS_BASE.map(rank => ({
        ...rank,
        contribution: Math.floor(rank.baseContribution * diff.rankMult),
        realmReq: entryRealm + (rank.realmOffset || 0)
    }));
}
